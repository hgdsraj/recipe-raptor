#!/usr/bin/env python3
"""
RecipeRaptor Build & Validation System
Compiles individual recipe files from `recipes/` into `data/recipes.json` and `js/recipes-data.js`.
"""

import os
import glob
import json
import sys

def build():
    recipes_dir = os.path.join(os.path.dirname(__file__), "recipes")
    data_dir = os.path.join(os.path.dirname(__file__), "data")
    js_dir = os.path.join(os.path.dirname(__file__), "js")

    os.makedirs(data_dir, exist_ok=True)
    os.makedirs(js_dir, exist_ok=True)

    json_files = glob.glob(os.path.join(recipes_dir, "*.json"))
    if not json_files:
        print("❌ Error: No recipe files found in 'recipes/' directory!")
        sys.exit(1)

    recipes = []
    seen_ids = set()
    errors = []

    for file_path in sorted(json_files):
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                data = json.load(f)

            # Validation
            recipe_id = data.get("id")
            if not recipe_id:
                errors.append(f"{file_path}: missing 'id'")
                continue
            if recipe_id in seen_ids:
                errors.append(f"Duplicate recipe id '{recipe_id}' in {file_path}")
            seen_ids.add(recipe_id)

            title = data.get("title")
            if not title:
                errors.append(f"{file_path}: missing 'title'")

            # Ensure nutrition structure
            if "macros" not in data:
                data["macros"] = {"protein_g": 25, "carbs_g": 35, "fat_g": 15}
            if "micros" not in data:
                data["micros"] = {"fiber_g": 4, "sodium_mg": 500, "iron_mg": 2.5, "potassium_mg": 450, "vitamin_c_mg": 15, "calcium_mg": 80}

            recipes.append(data)
        except Exception as e:
            errors.append(f"{file_path}: {e}")

    if errors:
        print(f"⚠️ Validation warnings/errors ({len(errors)}):")
        for err in errors:
            print(f"  • {err}")

    # Sort recipes by title
    recipes.sort(key=lambda r: r.get("title", "").lower())

    # Write data/recipes.json
    out_json = os.path.join(data_dir, "recipes.json")
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(recipes, f, indent=2, ensure_ascii=False)

    # Write js/recipes-data.js
    out_js = os.path.join(js_dir, "recipes-data.js")
    with open(out_js, "w", encoding="utf-8") as f:
        f.write("// RecipeRaptor Master Recipe Database\n")
        f.write("// Auto-generated by build.py — do not edit manually\n")
        f.write("window.RECIPES_DATA = ")
        json.dump(recipes, f, indent=2, ensure_ascii=False)
        f.write(";\n")

    # Stats
    categories = {}
    proteins = {}
    for r in recipes:
        cat = r.get("category", "Other")
        categories[cat] = categories.get(cat, 0) + 1
        prot = r.get("protein", "Other")
        proteins[prot] = proteins.get(prot, 0) + 1

    print("=" * 60)
    print("🦖 RecipeRaptor Build Complete!")
    print(f"✅ Total Recipes Compiled: {len(recipes)}")
    print(f"📁 Master JSON: {out_json}")
    print(f"📁 Static JS Bundle: {out_js}")
    print("-" * 60)
    print("🥩 Protein Breakdown:")
    for p, count in sorted(proteins.items(), key=lambda x: -x[1]):
        print(f"   • {p:<20}: {count} recipes")
    print("-" * 60)
    print("🍽️  Category Breakdown:")
    for c, count in sorted(categories.items(), key=lambda x: -x[1]):
        print(f"   • {c:<20}: {count} recipes")
    print("=" * 60)

if __name__ == "__main__":
    build()
